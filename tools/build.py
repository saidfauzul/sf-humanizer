#!/usr/bin/env python3
"""Build skill examples and preset metric profiles from samples/. Standard library only.

Examples: at most MAX_EXAMPLE_BYTES per preset, with the first good sample and the two pairs
listing the most distinct pattern ids. Longer texts are cut at a paragraph or sentence
boundary so that all three fit, and the cut is marked.

Profiles: metrics computed on each good text and After text of a preset, written as a
`metrics:` block in the frontmatter of references/presets/<lang>-<register>.md. A preset file
that does not exist yet is created as a stub.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import validate  # noqa: E402

MAX_EXAMPLE_BYTES = 6 * 1024
EXAMPLES_PATH = Path("skill/sf-humanizer/references/examples")
PRESETS_PATH = Path("skill/sf-humanizer/references/presets")
PATTERN_ID = re.compile(r"\b(?:ID|EN)-\d{2}\b")
SECTION_RE = re.compile(r"^## .*$", re.MULTILINE)
METRICS_BLOCK = re.compile(r"^metrics:\n(?:[ \t]+.*\n)*", re.MULTILINE)
CUT_MARK = {"id": "[dipotong]", "en": "[cut]"}
HEADINGS = {
    "id": ("Contoh baik", "Pasangan", "Sebelum", "Sesudah", "Catatan"),
    "en": ("Good example", "Pair", "Before", "After", "Notes"),
}
STUB_BODY = {
    "id": "Panduan register ini menyusul pada Tahap 4.",
    "en": "Guidance for this register arrives in Tahap 4.",
}
PROFILE_KEYS = (
    ("mean_sentence_length", "sentences", "mean_length"),
    ("light_verbs_per_100_words", "light_verbs", "per_100_words"),
    ("connectors_per_100_sentences", "connectors", "per_100_sentences"),
    ("nominalizations_per_100_words", "nominalizations", "per_100_words"),
    ("merupakan_per_100_words", "merupakan", "per_100_words"),
)


def load_metrics():
    path = REPO / "skill" / "sf-humanizer" / "scripts" / "metrics.py"
    spec = importlib.util.spec_from_file_location("sf_humanizer_metrics", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


metrics = load_metrics()


def body_of(text: str) -> str:
    return text.split("---\n", 2)[2].strip()


def read_samples(root: Path, language: str, register: str) -> tuple[list[dict], list[dict]]:
    """Return the good samples and pairs of a preset, sorted by id."""
    folder = root / "samples" / language / register
    goods = []
    for path in sorted((folder / "good").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        goods.append({"id": validate.parse_frontmatter(text)["id"], "text": body_of(text)})
    pairs = []
    for path in sorted((folder / "pairs").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        parts = [part.strip() for part in SECTION_RE.split(body_of(text))]
        pairs.append(
            {
                "id": validate.parse_frontmatter(text)["id"],
                "before": parts[1],
                "after": parts[2],
                "notes": parts[3],
            }
        )
    return goods, pairs


def pattern_count(pair: dict) -> int:
    return len(set(PATTERN_ID.findall(pair["notes"])))


def truncate(text: str, limit: int, mark: str) -> str:
    """Cut text to limit characters at a paragraph or sentence boundary."""
    if len(text) <= limit:
        return text
    head = text[:limit]
    for boundary in ("\n\n", ". ", "\n"):
        position = head.rfind(boundary)
        if position > limit // 3:
            return f"{head[: position + (boundary == '. ')].rstrip()}\n\n{mark}"
    return f"{head.rstrip()}\n\n{mark}"


def render_examples(
    language: str, register: str, goods: list[dict], pairs: list[dict], limit: int
) -> str:
    good_heading, pair_heading, before, after, notes = HEADINGS[language]
    mark = CUT_MARK[language]
    ranked = sorted(pairs, key=lambda pair: (-pattern_count(pair), pair["id"]))[:2]
    lines = [
        f"<!-- Generated by tools/build.py from samples/{language}/{register}/. Do not edit. -->",
        "",
        f"# {language}-{register}",
    ]
    for good in goods[:1]:
        lines += ["", f"## {good_heading}", "", truncate(good["text"], limit, mark)]
    for number, pair in enumerate(ranked, start=1):
        lines += [
            "",
            f"## {pair_heading} {number}",
            "",
            f"### {before}",
            "",
            truncate(pair["before"], limit, mark),
            "",
            f"### {after}",
            "",
            truncate(pair["after"], limit, mark),
            "",
            f"### {notes}",
            "",
            pair["notes"],
        ]
    return "\n".join(lines) + "\n"


def build_examples(language: str, register: str, goods: list[dict], pairs: list[dict]) -> str:
    """Render examples with the largest per-text limit that fits the cap."""
    for limit in range(4000, 100, -50):
        rendered = render_examples(language, register, goods, pairs, limit)
        if len(rendered.encode("utf-8")) <= MAX_EXAMPLE_BYTES:
            return rendered
    raise ValueError(f"examples for {language}-{register} cannot fit the size cap")


def percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    return round(ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower), 2)


def compute_profile(language: str, goods: list[dict], pairs: list[dict]) -> dict:
    """Return median and interquartile range for each profile metric."""
    reports = [
        metrics.analyze(text, language)["metrics"]
        for text in [good["text"] for good in goods] + [pair["after"] for pair in pairs]
    ]
    profile = {}
    for name, group, field in PROFILE_KEYS:
        if group == "merupakan" and language != "id":
            continue
        values = [report[group][field] for report in reports]
        profile[name] = {
            "median": percentile(values, 0.5),
            "p25": percentile(values, 0.25),
            "p75": percentile(values, 0.75),
        }
    return profile


def metrics_block(profile: dict) -> str:
    lines = ["metrics:"]
    for name, values in profile.items():
        lines.append(
            f"  {name}: {{median: {values['median']}, p25: {values['p25']}, p75: {values['p75']}}}"
        )
    return "\n".join(lines) + "\n"


def render_preset(existing: str | None, language: str, register: str, profile: dict) -> str:
    """Return the preset file with an updated metrics block."""
    block = metrics_block(profile)
    if existing is None:
        return (
            f"---\nname: {language}-{register}\nlang: {language}\nregister: {register}\n"
            f"status: stub\n{block}---\n\n{STUB_BODY[language]}\n"
        )
    head, separator, rest = existing.partition("\n---\n")
    if not separator:
        raise ValueError(f"preset {language}-{register} has no frontmatter")
    head += "\n"
    if METRICS_BLOCK.search(head):
        head = METRICS_BLOCK.sub(lambda _: block, head)
    else:
        head += block
    return f"{head.rstrip()}\n---\n{rest}"


def build(root: Path) -> dict[Path, str]:
    """Return generated files, keyed by path relative to root."""
    outputs: dict[Path, str] = {}
    for language, registers in validate.REGISTERS.items():
        for register in registers:
            goods, pairs = read_samples(root, language, register)
            if not goods and not pairs:
                continue
            name = f"{language}-{register}.md"
            outputs[EXAMPLES_PATH / name] = build_examples(language, register, goods, pairs)
            preset = root / PRESETS_PATH / name
            existing = preset.read_text(encoding="utf-8") if preset.is_file() else None
            profile = compute_profile(language, goods, pairs)
            outputs[PRESETS_PATH / name] = render_preset(existing, language, register, profile)
    return outputs


def write(root: Path, outputs: dict[Path, str]) -> None:
    for relative, content in outputs.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def stale_files(root: Path, outputs: dict[Path, str]) -> list[Path]:
    """Return generated paths that differ from the committed files."""
    stale = []
    for relative, content in outputs.items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(relative)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build skill examples and preset profiles.")
    parser.add_argument("--root", type=Path, default=REPO, help="repository root")
    parser.add_argument("--check", action="store_true", help="fail if outputs are out of date")
    args = parser.parse_args(argv)

    outputs = build(args.root)
    if args.check:
        stale = stale_files(args.root, outputs)
        for path in stale:
            print(f"error: {path} is out of date; run tools/build.py", file=sys.stderr)
        if stale:
            return 1
        print("build: up to date")
        return 0

    write(args.root, outputs)
    print(f"build: wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
