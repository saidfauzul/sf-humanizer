from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent

spec = importlib.util.spec_from_file_location("build", REPO_ROOT / "tools" / "build.py")
build = importlib.util.module_from_spec(spec)
sys.modules["build"] = build
spec.loader.exec_module(build)

LONG = "\n\n".join(
    "Panitia menerima dokumen itu pada pagi hari dan memeriksa isinya dengan teliti." * 4
    for _ in range(6)
)


def write_sample(root: Path, kind: str, number: int, notes: str = "ID-01.", text: str = LONG):
    folder = "good" if kind == "good" else "pairs"
    sample_id = f"id-formal-{kind}-{number:03d}"
    path = root / "samples/id/formal" / folder / f"{sample_id}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    frontmatter = f"---\nid: {sample_id}\nkind: {kind}\nnotes: {notes}\n---\n\n"
    body = (
        text
        if kind == "good"
        else f"## Sebelum\n\n{text}\n\n## Sesudah\n\n{text}\n\n## Catatan\n\n{notes}\n"
    )
    path.write_text(frontmatter + body + "\n", encoding="utf-8")


@pytest.fixture
def root(tmp_path: Path) -> Path:
    write_sample(tmp_path, "good", 1)
    write_sample(tmp_path, "pair", 1, "ID-01.")
    write_sample(tmp_path, "pair", 2, "ID-01, ID-02, ID-03.")
    write_sample(tmp_path, "pair", 3, "ID-04, ID-05.")
    return tmp_path


def test_examples_respect_cap_and_mark_cuts(root: Path) -> None:
    outputs = build.build(root)
    content = outputs[build.EXAMPLES_PATH / "id-formal.md"]
    assert len(content.encode("utf-8")) <= build.MAX_EXAMPLE_BYTES
    assert "[dipotong]" in content
    assert content.startswith("<!-- Generated by tools/build.py")


def test_short_texts_are_not_cut(root: Path) -> None:
    write_sample(root, "good", 1, text="Teks pendek sekali.")
    for number in (1, 2, 3):
        write_sample(root, "pair", number, text="Teks pendek sekali.")
    content = build.build(root)[build.EXAMPLES_PATH / "id-formal.md"]
    assert "[dipotong]" not in content


def test_pairs_ranked_by_distinct_pattern_ids(root: Path) -> None:
    content = build.build(root)[build.EXAMPLES_PATH / "id-formal.md"]
    assert "ID-01, ID-02, ID-03." in content
    assert "ID-04, ID-05." in content
    assert "\nID-01.\n" not in content


def test_stub_preset_created_with_metrics(root: Path) -> None:
    content = build.build(root)[build.PRESETS_PATH / "id-formal.md"]
    assert "status: stub" in content
    assert "name: id-formal" in content
    assert "mean_sentence_length: {median:" in content
    assert "merupakan_per_100_words" in content


def test_existing_preset_keeps_content(root: Path) -> None:
    path = root / build.PRESETS_PATH / "id-formal.md"
    path.parent.mkdir(parents=True)
    path.write_text(
        "---\nname: id-formal\nmetrics:\n  old: 1\nstatus: ready\n---\n\nIsi.\n", "utf-8"
    )
    content = build.build(root)[build.PRESETS_PATH / "id-formal.md"]
    assert "old: 1" not in content
    assert "status: ready" in content
    assert content.endswith("\n---\n\nIsi.\n")
    assert content.count("metrics:") == 1


def test_percentile() -> None:
    assert build.percentile([1, 2, 3, 4], 0.5) == 2.5
    assert build.percentile([5], 0.25) == 5


def test_presets_without_samples_are_skipped(root: Path) -> None:
    assert len(build.build(root)) == 2


def test_check_mode(root: Path) -> None:
    assert build.main(["--root", str(root), "--check"]) == 1
    assert build.main(["--root", str(root)]) == 0
    assert build.main(["--root", str(root), "--check"]) == 0
    write_sample(root, "pair", 4, "ID-01, ID-02, ID-03, ID-04.")
    assert build.main(["--root", str(root), "--check"]) == 1


def test_build_is_stable_after_writing(root: Path) -> None:
    build.main(["--root", str(root)])
    assert build.stale_files(root, build.build(root)) == []


def test_committed_outputs_are_current() -> None:
    assert build.stale_files(REPO_ROOT, build.build(REPO_ROOT)) == []
